// Bakes the resume-tailor source files into src/assets.ts as JSON-escaped
// strings, so both the deployed Worker (no fs) and node tests import the same
// plain .ts module. Re-run after editing master_resume.md or best_practices.md.
//
//   node scripts/bundle-assets.mjs
import { readFileSync, writeFileSync } from "node:fs";
import { homedir } from "node:os";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const RT = join(homedir(), "resume-tailor");
const master = readFileSync(join(RT, "master_resume.md"), "utf8");
const best = readFileSync(join(RT, "best_practices.md"), "utf8");

// GOLD_PREAMBLE + GOLD_EXAMPLE come from an approved, compiled resume (a real
// one-page artifact), NOT retyped from tailor.md's prose block. Preamble = up to
// \section{EDUCATION}; example = the whole file.
const gold = readFileSync(
  join(RT, "tex", "resume_Apple_SoftwareEngineerISTEarlyCareer.tex"),
  "utf8",
);
const preamble = gold.split("\\section{EDUCATION}")[0].trimEnd();

// GOLD_EXAMPLE: the full approved Salesforce resume, a real one-page artifact.
// The drafter sees it as a length/density template so it stops overshooting to
// two pages. Content is tailored to a DIFFERENT job, so the prompt is explicit
// that it's a shape reference, not something to copy.
const out = `// GENERATED by scripts/bundle-assets.mjs — do not edit by hand.
export const MASTER_RESUME = ${JSON.stringify(master)};
export const BEST_PRACTICES = ${JSON.stringify(best)};
export const GOLD_PREAMBLE = ${JSON.stringify(preamble)};
export const GOLD_EXAMPLE = ${JSON.stringify(gold)};
`;

const dir = dirname(fileURLToPath(import.meta.url));
writeFileSync(join(dir, "..", "src", "assets.ts"), out);
console.log(
  `wrote src/assets.ts (master ${master.length}b, best ${best.length}b, preamble ${preamble.length}b)`,
);
